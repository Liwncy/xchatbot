export function translateTag(raw: string): string {
    const trimmed = String(raw).trim().replace(/[#[\]【】]/gu, '');
    if (!trimmed) return '';
    if (HAS_CJK.test(trimmed)) return trimmed.slice(0, 12);
    const key = trimmed.toLowerCase().replace(/\s+/g, '_');
    return (EMOJI_TAG_ZH[key] ?? EMOJI_TAG_ZH[key.replace(/-/g, '_')]) || '';
}

export function translateTags(tags: string[] | undefined): string[] {
    if (!tags?.length) return [];
    const out: string[] = [];
    for (const raw of tags) {
        const zh = translateTag(raw);
        if (!zh || !HAS_CJK.test(zh)) continue;
        if (!out.includes(zh)) out.push(zh);
        if (out.length >= 6) break;
    }
    return out;
}

export function describeEmoji(
    name: string,
    tags: string[],
    category: EmojiStashCategory | string,
): string {
    const fromTags = translateTags(tags);
    const fromName = translateTags(name.split(/[_\s-]+/g));
    const merged: string[] = [];
    for (const item of [...fromName, ...fromTags]) {
        if (!merged.includes(item)) merged.push(item);
        if (merged.length >= 6) break;
    }
    if (merged.length) return merged.join('，');
    return EMOJI_STASH_CATEGORY_LABELS[category as EmojiStashCategory] ?? '表情';
}
